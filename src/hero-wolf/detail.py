for i, n in enumerate(names):
    x0 = 40 + i * 270
    d.text((x0, 16), n.upper(), fill=(255, 183, 74))
    d.rectangle([x0 - 20, 40 + 16 * Z, x0 + 240, 40 + 16 * Z + 8], fill=(74, 90, 208))
