Z = 12
def grid(s): return s.strip('\n').split('\n')
def draw_frame(img, ox, oy, g, tails):
    d = ImageDraw.Draw(img)
    def px(x, y, col): d.rectangle([ox + x * Z, oy + y * Z, ox + (x + 1) * Z - 1, oy + (y + 1) * Z - 1], fill=col)
    for (x, y, sz) in tails:
        for yy in range(y - 1, y + sz + 1):
            for xx in range(x - 1, x + sz + 1): px(xx, yy, C['o'])
    for i, (x, y, sz) in enumerate(tails):
        for yy in range(y, y + sz):
            for xx in range(x, x + sz): px(xx, yy, C['b'] if i == 0 else C['k'])
        if sz == 2: px(x, y, C['B'])
    for y, row in enumerate(g):
        for x, ch in enumerate(row):
            if ch != '.': px(x, y, C[ch])

names = ['idle', 'run', 'jump', 'wall', 'dash']
W, H = 60 + len(names) * 270, 20 * Z + 80
img = Image.new('RGB', (W, H), (10, 13, 28))
