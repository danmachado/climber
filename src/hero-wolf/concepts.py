def grid(s): return [l for l in s.strip('\n').split('\n')]

# bandana tails: chain nodes (x, y, size) relative to the frame, drawn before the body so they sit behind
TAILS = {
    'A_IDLE': [(3, 6, 2), (2, 8, 2), (2, 10, 1), (1, 12, 1)],
    'A_DASH': [(3, 9, 2), (1, 9, 2), (-1, 10, 1), (-3, 10, 1)],
    'B_IDLE': [(5, 4, 2), (4, 6, 2), (4, 8, 1), (3, 10, 1)],
    'B_DASH': [(4, 8, 2), (2, 8, 2), (0, 9, 1), (-2, 9, 1)],
    'C_IDLE': [(2, 5, 2), (1, 7, 2), (1, 9, 1), (0, 11, 1)],
    'C_DASH': [(2, 7, 2), (0, 7, 2), (-2, 8, 1), (-4, 8, 1)],
}

Z = 12
def draw_frame(img, ox, oy, g, tails, afterimages=False):
    d = ImageDraw.Draw(img)
    def px(x, y, col): d.rectangle([ox + x * Z, oy + y * Z, ox + (x + 1) * Z - 1, oy + (y + 1) * Z - 1], fill=col)
    if afterimages:                                  # dash trail: two flat silhouettes behind, in bandana red then skin
        for k, (dx, col) in enumerate([(-7, (110, 34, 30))]):
            for y, row in enumerate(g):
                for x, ch in enumerate(row):
                    if ch != '.': px(x + dx, y, col)
    for (x, y, sz) in tails:                         # outline then fill, like the game will draw the chain
        for yy in range(y - 1, y + sz + 1):
            for xx in range(x - 1, x + sz + 1): px(xx, yy, C['o'])
    for (x, y, sz) in tails:
        for yy in range(y, y + sz):
            for xx in range(x, x + sz): px(xx, yy, C['k'] if sz == 1 else C['b'])
    for y, row in enumerate(g):
        for x, ch in enumerate(row):
            if ch != '.': px(x, y, C[ch])

