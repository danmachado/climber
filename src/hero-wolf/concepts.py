for i, (name, idle, dash, key) in enumerate(designs):
    x0 = 20 + i * 420
    d.text((x0 + 8, 12), name, fill=(255, 183, 74))
    d.text((x0 + 8, 30), 'idle', fill=(154, 166, 204)); d.text((x0 + 8, 300), 'dash', fill=(154, 166, 204))
    # floor line
    d.rectangle([x0, 50 + 16 * Z, x0 + 400, 50 + 16 * Z + 6], fill=(74, 90, 208))
    d.rectangle([x0, 320 + 16 * Z, x0 + 400, 320 + 16 * Z + 6], fill=(74, 90, 208))
    draw_frame(img, x0 + 110, 50, grid(idle), TAILS[key + '_IDLE'])
    draw_frame(img, x0 + 140, 320, grid(dash), TAILS[key + '_DASH'], afterimages=True)
    # hitbox guide on the idle pose
    d.rectangle([x0 + 110 + 4 * Z, 50 + 6 * Z, x0 + 110 + 12 * Z - 1, 50 + 16 * Z - 1], outline=(95, 230, 180))
